-- 관리자 화면에서 저장하면서 9시간 밀린 시각을 되돌린다.
--
-- datetime-local은 시간대가 없는 문자열로 온다. 그것을 받는 곳이 서버 액션이라
-- 서버 시간대로 읽혔는데, 개발 기기는 한국이고 Vercel은 UTC다. 그래서 로컬에서
-- 는 멀쩡하고 배포본에서만 밀렸다 — 21:00으로 넣은 것이 다음 날 06:00으로
-- 저장됐다.
--
-- 받는 쪽은 +09:00으로 못 박아 고쳤다. 여기서는 그 사이에 어긋난 값을 되돌린다.
update public.mentor_sessions
set opens_at  = timestamptz '2026-09-06 21:00:00+09',
    closes_at = timestamptz '2026-09-12 12:30:00+09',
    starts_at = timestamptz '2026-09-12 10:30:00+09';
