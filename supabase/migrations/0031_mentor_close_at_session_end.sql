-- 신청 마감은 멘토님 시간이 끝날 때까지.
--
-- 처음에는 "세션 전날까지"로 두었다. 당일에 옮겨 다니면 멘토님이 몇 명을
-- 맞이할지 모른 채 들어가시게 되기 때문이다.
--
-- 실제로는 그날 아침에야 오는 사람이 있고, 옆방이 비어 있는데 못 옮기는
-- 편이 더 아깝다. 시간이 끝날 때까지 열어 둔다 — 어차피 끝난 뒤에는
-- 바꿀 이유가 없다.
--
-- 일정표의 멘토의 TMI는 9.12(토) 10:30~12:30이다.
update public.mentor_sessions
set closes_at = timestamptz '2026-09-12 12:30:00+09'
where closes_at <> timestamptz '2026-09-12 12:30:00+09';
